export function getMockSFXLibraryScenarioById(id: string): MockSFXLibraryScenario | undefined {
  return mockSFXLibraryScenarios.find((scenario) => scenario.id === id)
}

export function getDefaultMockSFXLibraryScenario(): MockSFXLibraryScenario {
  return mockSFXLibraryScenarios[0]
}

export function getMockSFXLibraryQAScenario(scenario: MockSFXLibraryScenario): MockSFXQAScenario {
  return getMockSFXQAScenarioById(scenario.qaScenarioId) ?? getDefaultMockSFXQAScenario()
}
